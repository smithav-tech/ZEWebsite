"""Trace every doodle in design/doodles/ and write src/client/ink/traced.ts.

usage: python scripts/build_traced.py

Each image is traced into one continuous stroke (trace_doodle.py), then trimmed
to the drawing: Gemini draws the line in from the far edge and out again, and
those long entry and exit strokes would leave the drawing small in its box.
The trim keeps the path from the first point inside `crop` to the last, so the
scene still enters from the side and leaves heading down, and the box is the
drawing.
"""
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# key, const, image, entry, exit, crop (x0, y0, x1, y1 in the trace's own units), description
# and, for fine detail, extra tracer options (a higher resolution, lighter smoothing)
FINE = ["--eps", "0.9", "--work", "2048", "--smooth", "3"]

SCENES = [
    ("cow", "HERO", "1-hero-cow-calf", "left", "bottom", (120, 0, 829, 400), "the hero: a dairy cow nursing her calf", FINE),
    ("methane", "METHANE", "2-methane", "left", "bottom", (110, 0, 1014, 830), "CH4OW: a contented cow burping a string of round methane bubbles",
     [*FINE, "--gap", "160"]),
    ("feed", "FEED", "3-feed", "left", "bottom", (60, 0, 1024, 500), "feed and TMR: fodder grass, a bowl of TMR, a tractor hauling bales", FINE),
    ("energy", "ENERGY", "4-energy", "left", "bottom", (90, 0, 923, 560), "green energy: fodder, cow, manure, biogas plant and CBG, fertiliser, round again"),
    ("corridor", "CORRIDOR", "5-corridor", "left", "right", (40, 0, 1024, 670), "the corridor: cow, feed, tractor, milk, biogas and data on one road"),
    ("gramcarbon", "GRAMCARBON", "6-gramcarbon", "left", "bottom", (140, 0, 953, 230), "gramCarbon: the line writes the wordmark, the logo's three petals for its r", FINE),
    ("offsets", "OFFSETS", "7-carbon-value", "left", "bottom", (150, 0, 869, 740), "carbon value: the ZE SITA coin, a front-facing tagged cow's head inside two rims", FINE),
]

NUM = r"-?\d+(?:\.\d+)?"


def parse(d):
    nums = [float(n) for n in re.findall(NUM, d)]
    start = (nums[0], nums[1])
    segs = [tuple(nums[i : i + 6]) for i in range(2, len(nums), 6)]
    return start, segs


def trim(d, crop):
    x0, y0, x1, y1 = crop
    inside = lambda x, y: x0 <= x <= x1 and y0 <= y <= y1
    start, segs = parse(d)
    ends = [start] + [(s[4], s[5]) for s in segs]
    first = next(i for i, p in enumerate(ends) if inside(*p))
    last = max(i for i, p in enumerate(ends) if inside(*p))
    keep = segs[first:last]
    sx, sy = ends[first]
    r = lambda v: str(round(v))
    parts = [f"M{r(sx - x0)},{r(sy - y0)}"]
    for c in keep:
        parts.append(
            "C" + ",".join([r(c[0] - x0), r(c[1] - y0)]) + " " + ",".join([r(c[2] - x0), r(c[3] - y0)]) + " " + ",".join([r(c[4] - x0), r(c[5] - y0)])
        )
    return " ".join(parts), round(x1 - x0), round(y1 - y0)


def main():
    out = [
        "/**",
        " * The doodles, traced from the approved freehand one-line drawings",
        " * (design/doodles/). Each is a single continuous stroke in its own w x h box,",
        " * absolute M + C commands only: it enters from the side and leaves heading",
        " * down, and where the original drawing branches, the pen runs back over a",
        " * stroke exactly so the whole picture stays one line.",
        " *",
        " * Generated by scripts/build_traced.py (trace_doodle.py: threshold, thin to a",
        " * centreline, one route over every stroke, Catmull-Rom curves; then trimmed",
        " * to the drawing); edit the drawings, not these numbers.",
        " */",
        "",
    ]
    tmp = tempfile.mkdtemp()
    for key, const, image, entry, exit_, crop, desc, *extra in SCENES:
        opts = extra[0] if extra else ["--eps", "1.5"]
        prefix = os.path.join(tmp, key)
        subprocess.run(
            [sys.executable, os.path.join(HERE, "trace_doodle.py"), os.path.join(ROOT, "design", "doodles", image + ".png"), prefix,
             "--entry", entry, "--exit", exit_, *opts],
            check=True, capture_output=True,
        )
        j = json.load(open(prefix + ".json"))
        d, w, h = trim(j["d"], crop)
        print(key, w, h, d.count("C"), "segments", j["stats"]["retraced_edges"], "retraced")
        out.append(f"/** {desc} */")
        out.append(f'export const {const} = {{ w: {w}, h: {h}, d: "{d}" }};')
        out.append("")
    open(os.path.join(ROOT, "src", "client", "ink", "traced.ts"), "w", encoding="utf-8").write("\n".join(out))
    print("previews in", tmp)


if __name__ == "__main__":
    main()
